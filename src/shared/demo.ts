export const demoVehicles: Vehicle[] = cars.map((car, i) => {
  const n = String(i + 1).padStart(3, "0");
  const name = `${car.make} ${car.model}`;
  const photo = samplePhotos[name];
  return vehicleSchema.parse({
    ...car,
    currency: "USD",
    mileageUnit: car.mileageUnit ?? "mi",
    _id: `demo-${i + 1}`,
    title: `${car.year} ${name}${car.trim ? ` ${car.trim}` : ""}`,
    stockId: `DEMO-${n}`,
    firstRegistration: `${car.year}-01-15`,
    dealerId: car.dealerId ?? demoDealer._id,
    location: car.location ?? "Los Angeles, CA",
    description:
      car.category === "trailer"
        ? `${car.year} ${name} ${car.bodyStyle.toLowerCase()} with ${car.axles} axles and a ${car.payload?.toLocaleString("en-US")} kg payload. ${disclaimer}`
        : `${car.year} ${name} with ${car.mileage.toLocaleString("en-US")} ${car.mileageUnit ?? "mi"}, ${car.fuel.toLowerCase()} engine and ${(car.transmission ?? "Automatic").toLowerCase()} transmission. ${disclaimer}`,
    taxDisclaimer: "Prices exclude registration and documentation fees.",
    media: [
      photo
        ? {
            url: samplePhotoPath(photo.file),
            alt: `${name} (sample photo)`,
            credit: photo.credit,
            creditUrl: photo.creditUrl,
          }
        : {
            url: "/media/demo-car.svg",
            alt: `Illustration of a sample ${name}`,
          },
    ],
    seoTitle: `${car.year} ${name} for sale`.slice(0, 70),
    status: "draft",
    demo: true,
    featured: i < 2 || i === 5,
    slug: `demo-${i + 1}`,
    createdAt: date,
    updatedAt: date,
  });
});
